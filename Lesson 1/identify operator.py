operator = input("Enter an operator (+, -, *, /): ")

if operator == "+":
    print("You entered Addition operator.")
elif operator == "-":
    print("You entered Subtraction operator.")
elif operator == "*":
    print("You entered Multiplication operator.")
elif operator == "/":
    print("You entered Division operator.")
else:
    print("Invalid operator.")

print("Congratulations! You completed the activity! ")