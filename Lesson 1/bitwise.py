num1 = int(input("Enter the first number: "))
num2 = int(input("Enter the second number: "))

# Bitwise AND
print("Bitwise AND (&):", num1 & num2)

# Bitwise OR
print("Bitwise OR (|):", num1 | num2)

# Bitwise XOR
print("Bitwise XOR (^):", num1 ^ num2)

# Bitwise NOT
print("Bitwise NOT (~) of first number:", ~num1)

# Left Shift
print("Left Shift (<<):", num1 << 1)

# Right Shift
print("Right Shift (>>):", num1 >> 1)

print("\nCongratulations! You completed the Bitwise Operators activity! ")